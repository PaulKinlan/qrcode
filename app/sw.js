import {router} from  './scripts/sw/router.js';

/*
  Cache names carry the app version, which the build injects from package.json
  (`define: {__APP_VERSION__}` in vite.config.js). Bumping package.json therefore invalidates
  the offline cache, and there is no second place to remember to bump.
*/
const VERSION = __APP_VERSION__;
const CACHE_PREFIX = 'qr-precache-';
const PRECACHE_CACHE = `${CACHE_PREFIX}${VERSION}`;
// Consent survives a worker restart while an offline confirmation page is open. The same
// version prefix lets the existing kill/activation cleanup remove this cache with the precache.
const CONSENT_CACHE = `${PRECACHE_CACHE}-consent`;
const CONSENT_URL = `${self.location.origin}/__kill-sw-consent`;
const CONSENT_TTL_MS = 10 * 60 * 1000;
const CONSENT_MAX = 4;
let consentQueue = Promise.resolve();

// Serialize read-modify-write operations so concurrent asks/submissions cannot lose a token.
const withConsentStore = (operation) => {
  const result = consentQueue.then(operation);
  consentQueue = result.catch(() => {});
  return result;
};

const readConsent = async (cache) => {
  try {
    const response = await cache.match(CONSENT_URL);
    const tokens = response ? await response.json() : [];
    return Array.isArray(tokens) ? tokens : [];
  } catch {
    return []; // Corrupt or evicted storage must never grant consent.
  }
};

const writeConsent = (cache, tokens) => cache.put(CONSENT_URL,
  new Response(JSON.stringify(tokens), {headers: {'Content-Type': 'application/json'}}));

const mintConsent = () => withConsentStore(async () => {
  const cache = await caches.open(CONSENT_CACHE);
  const now = Date.now();
  const tokens = (await readConsent(cache))
    .filter((entry) => entry && typeof entry.token === 'string' && entry.expires > now)
    .slice(-(CONSENT_MAX - 1));
  const token = Array.from(crypto.getRandomValues(new Uint8Array(16)),
    (byte) => byte.toString(16).padStart(2, '0')).join('');
  tokens.push({token, expires: now + CONSENT_TTL_MS});
  await writeConsent(cache, tokens);
  return token;
});

const consumeConsent = (candidate) => {
  if (typeof candidate !== 'string' || !/^[0-9a-f]{32}$/.test(candidate)) return Promise.resolve(false);
  return withConsentStore(async () => {
    const cache = await caches.open(CONSENT_CACHE);
    const now = Date.now();
    const tokens = (await readConsent(cache))
      .filter((entry) => entry && typeof entry.token === 'string' && entry.expires > now);
    const index = tokens.findIndex((entry) => entry.token === candidate);
    if (index < 0) return false;
    tokens.splice(index, 1);
    await writeConsent(cache, tokens); // Burn before any destructive work; replay must only ask.
    return true;
  });
};

/*
  The precache list is generated at build time by walking dist/ (vite.config.js,
  generatePrecacheManifest) into /sw-manifest.json. Adding an asset needs no edit here.
*/
const PRECACHE_MANIFEST_URL = '/sw-manifest.json';

/*
  Resolve one manifest entry to a precache URL, refusing anything that leaves this origin.

  The list used to be built by string concatenation (`/${file}`), so an entry such as
  `//evil.com/x.js` - or `/\evil.com/x.js`, which the URL parser reads the same way - became a
  third-party URL, and cache.addAll() would fetch and store that response for the fetch handler to
  serve on same-origin requests (bead qrcode-g3y, threat-model invariant 6: every manifest entry is
  a same-origin relative path). The manifest is generated from dist/ at build time, so this is
  defence in depth: a violating entry fails the install loudly instead of caching a foreign file.
*/
const toPrecacheUrl = (entry) => {
  if (typeof entry !== 'string' || entry.trim() === '') {
    throw new Error(`precache manifest entry must be a non-empty string: ${JSON.stringify(entry)}`);
  }

  const url = new URL(entry, `${self.location.origin}/`);
  if (url.origin !== self.location.origin) {
    throw new Error(`precache manifest entry ${JSON.stringify(entry)} resolves off-origin to ${url.origin}`);
  }

  return url.href;
};

/*
  The two pages the escape hatch can answer with. They are generated by the worker rather than
  fetched, so the confirmation works from the cache even when the network is gone - the state this
  hatch exists to get out of. No <script> at all: the confirmation is a plain GET form, so it needs
  no 'unsafe-inline' and no JS.
*/
const killPageHeaders = {
  'Content-Type': 'text/html; charset=utf-8',
  // The response is synthesised here, so the app's own <meta> policy in index.html does not apply:
  // without this header the page would be served with no policy whatsoever. Everything the page
  // needs is inline CSS and one same-origin form submission.
  'Content-Security-Policy': "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; " +
    "form-action 'self'; frame-ancestors 'none'",
  // Same-origin Referer remains one consent proof; a persisted single-use form token is the
  // fallback when privacy settings suppress it (beads qrcode-8vv, qrcode-3bd).
  'Referrer-Policy': 'same-origin',
  'X-Content-Type-Options': 'nosniff',
  'Cache-Control': 'no-store'
};

const killPage = (title, heading, body) => new Response(`<!doctype html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>
  body { font-family: system-ui, sans-serif; line-height: 1.5; margin: 0 auto; max-width: 32rem; padding: 2rem 1rem; color: #212121; }
  h1 { font-size: 1.5rem; }
  button, a { font-size: 1rem; }
  button { background: #0d47a1; border: 0; border-radius: .25rem; color: #fff; padding: .75rem 1rem; }
  button:focus-visible, a:focus-visible { outline: 3px solid #212121; outline-offset: 2px; }
</style>
</head>
<body>
<main>
<h1>${heading}</h1>
${body}
</main>
</body>
</html>`, {status: 200, headers: killPageHeaders});

/*
  Escape hatch, in two steps: unregister this worker and clear its precache on an explicit
  kill-sw=true request, but only after the user has confirmed it on the page below.

  Scoped to the EXACT same-origin root URL. This route used to match on the whole origin, so a
  `?kill-sw=true` on any same-origin URL - a subresource fetch, a shared or bookmarked link -
  unregistered the worker and wiped the offline cache (bead qrcode-1ks). The pathname alone is not
  a sufficient scope either: the worker's fetch listener also sees third-party subresources, whose
  pathname can be '/', so the predicate requires this origin as well (bead qrcode-6a3). Only a
  navigation to `/?kill-sw=true` on this origin arms it: a cross-site image or fetch of that URL
  must not unregister the worker. Every other request keeps the normal behaviour.

  `unregister()` followed by `caches.delete()` is irreversible from the page, so a single
  navigable link must not be enough to run it: a shared, shortened or bookmarked URL that the user
  clicks once used to destroy the installed app's offline capability with no warning and no undo
  (bead qrcode-78c). The route is therefore split:

   - without `confirm=1` it only ANSWERS with the confirmation page and touches nothing, so the
     worst a drive-by link can do is show a page;
   - with `confirm=1`, which the page's form submits, it does the cleanup and answers with the
     result. Doing the work inside respondWith (not waitUntil) means the page the user lands on is
     the one produced AFTER the cleanup, so it cannot claim success before it is true.

  `confirm=1` alone is not enough to prove consent, because it is a public URL token: a crafted
  link to `/?kill-sw=true&confirm=1` would otherwise wipe the offline copy with no page and no
  click at all (review finding qrcode-8vv). The destructive navigation must therefore come FROM the
  confirmation page. Its same-origin referrer is one proof; browsers that strip Referer use a
  worker-minted, single-use consent token stored until the form is submitted, even if the worker
  restarts. A public or forged URL without either proof only shows the ask page. The token is never
  a static/documented URL parameter; used tokens are burned before destructive work.
*/
const isOwnConfirmationPage = (referrer) => {
  if (typeof referrer !== 'string' || referrer === '') return false;

  try {
    const url = new URL(referrer);
    return url.origin === self.location.origin &&
      url.pathname === '/' &&
      url.searchParams.get('kill-sw') === 'true';
  } catch {
    // An unparseable referrer is not proof of consent.
    return false;
  }
};

const askPage = async () => {
  // Storage can be disabled; keep the old Referer-only path usable rather than failing the page.
  const token = await mintConsent().catch(() => null);
  return killPage('Turn off offline mode?', 'Turn off offline mode?',
    '<p>This link asks the app to remove its offline copy: the service worker is unregistered ' +
    'and the cached files are deleted. Scanning still works, but the app will need a network ' +
    'connection until you open it online again.</p>' +
    '<form method="get" action="/">' +
    '<input type="hidden" name="kill-sw" value="true">' +
    '<input type="hidden" name="confirm" value="1">' +
    (token ? `<input type="hidden" name="consent" value="${token}">` : '') +
    '<button type="submit">Turn off offline mode</button>' +
    '</form>' +
    '<p><a href="/">Keep offline mode</a></p>');
};

router.get('/', function(event) {
  const url = new URL(event.request.url);
  const confirmed = url.searchParams.get('confirm') === '1';

  event.respondWith((async () => {
    // A public confirm=1 URL is never consent. The form's unguessable, single-use token is
    // a fallback when Referer is stripped; an existing valid Referer still works unchanged.
    const fromAskPage = isOwnConfirmationPage(event.request.referrer);
    const tokenValid = confirmed && !fromAskPage && await consumeConsent(url.searchParams.get('consent'))
      .catch(() => false);
    if (!confirmed || (!fromAskPage && !tokenValid)) return askPage();

    try {
      await self.registration.unregister();
      const keys = await caches.keys();
      await Promise.all(keys.filter(key => key.startsWith(CACHE_PREFIX)).map(key => caches.delete(key)));
      return killPage('Offline mode is off', 'Offline mode is off',
        '<p>The offline copy has been removed: the service worker is unregistered and the cached ' +
        'files are deleted. Scanning works as normal.</p>' +
        '<p><a href="/">Open the app</a> (online) to turn offline mode back on.</p>');
    } catch (error) {
      console.error('kill switch failed', error);
      // Wording matters here: unregister() may already have succeeded when cache deletion failed,
      // so "reload to try again" would be a lie - the worker is gone and a reload cannot retry the
      // cleanup. Say what is actually uncertain instead.
      return killPage('Offline mode could not be turned off', 'Offline mode could not be turned off',
        '<p>Something went wrong while removing the offline copy, so some offline files may still ' +
        'be stored on this device. Open the app online and turn it off again.</p>');
    }
  })());
}, {urlMatchProperty: "pathname", matches: (url, event) =>
  url.origin === self.location.origin &&
  url.searchParams.get('kill-sw') === 'true' &&
  event.request.mode === 'navigate'});

/*
  Serve this origin's cached assets first, falling back to the network on a miss.

  This is the only route that matches on "origin", and it must stay last: it answers every
  same-origin request, so a narrower route (the kill switch above) has to win first.
*/
router.get(`${self.location.origin}`, e => {
  e.respondWith(
    caches.match(e.request, {ignoreSearch:true, cacheName: PRECACHE_CACHE}).then(response => {
      return response || fetch(e.request);
    })
  );
}, {urlMatchProperty: "origin"});

self.addEventListener('activate', function(event) {
  event.waitUntil((async () => {
    // Never take over documents from the release that is being replaced (bead qrcode-kkh).
    //
    // A window client controlled by the predecessor may have loaded from its PRECACHE_CACHE.
    // Two things would go wrong if we proceeded with one still open:
    //   1. claiming it hands it to THIS worker, whose fetch route only ever reads PRECACHE_CACHE by
    //      name, so every asset the old document asks for by its old URL is a miss; and
    //   2. deleting the predecessor's cache is what made those misses fatal offline - the old worker
    //      would have served them from there.
    // Either alone breaks the document, and together they produced a tab running one build's module
    // graph against another build's cache. The predecessor cache and its clients are left alone; the
    // next activation (once those documents are gone) cleans up. install() below no longer calls
    // skipWaiting(), so the normal path never reaches here with a predecessor's client - this is
    // the guard for a browser that force-activates a waiting worker anyway.
    // A newly activated worker does not control the predecessor's windows yet: the default
    // matchAll() filter would omit precisely the clients whose cache must survive. Query all
    // windows when a predecessor cache exists. On a first install there is no old cache, so
    // an uncontrolled first-visit window must still be claimed for immediate offline use.
    const keys = await caches.keys();
    const stale = keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== PRECACHE_CACHE);
    if (stale.length > 0) {
      const windows = await self.clients.matchAll({type: 'window', includeUncontrolled: true});
      if (windows.length > 0) return;
    }

    // A versioned cache name means every release would otherwise leave its predecessor behind.
    // Only OUR caches may be removed: CacheStorage is per origin, and other applications or user
    // storage on the same origin must survive this worker activating (review finding qrcode-kr4 -
    // deleting every key not equal to this release's name was over-broad).
    await Promise.all(stale.map(key => caches.delete(key)));

    // Claiming is what makes a FIRST visit offline-capable in its first document: with no controlled
    // predecessor cache in the picture (see the guard above), so taking over is safe.
    await self.clients.claim();
  })());
});

self.addEventListener('install', function(e) {
  // Deliberately NO self.skipWaiting() (bead qrcode-kkh). Install finishes and the worker WAITS, so
  // the browser keeps the previous release's worker - and its precache - serving the documents it
  // already loaded, and the new release takes over once those documents are gone. skipWaiting()
  // activated this worker immediately, which is what produced documents running one build against
  // another build's cache.
  //
  // The cache list below is still fully populated during install, so an activation that follows a
  // finished install never has to precache anything.
  e.waitUntil((async () => {
    const response = await fetch(PRECACHE_MANIFEST_URL, {cache: 'no-store'});
    if (!response.ok) {
      throw new Error(`precache manifest ${PRECACHE_MANIFEST_URL} returned HTTP ${response.status}`);
    }

    const manifest = await response.json();
    if (manifest.version !== VERSION) {
      // A worker precaching a different release's assets would serve a mismatched app.
      throw new Error(`precache manifest is v${manifest.version} but this worker is v${VERSION}`);
    }

    // '/' is the navigable entry point; cache.addAll() fails the install if any asset 404s,
    // which is what turns a stale asset list into a visible failure instead of an offline 404.
    // Every manifest entry is resolved through toPrecacheUrl(), so a non-relative entry cannot
    // pull another origin's content into the precache (bead qrcode-g3y).
    const urls = ['/', ...manifest.files.map(toPrecacheUrl)];
    const cache = await caches.open(PRECACHE_CACHE);
    await cache.addAll(urls);
  })());
});
